def _(key, lang='uz', **kwargs):
    lang_dict = translations.get(lang, translations['uz'])
    text = lang_dict.get(key, translations['uz'].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except KeyError:
            return text
    return text

def get_all_translations(key):
    variants = set()
    for lang_dict in translations.values():
        if key in lang_dict:
            variants.add(lang_dict[key])
        else:
            variants.add(translations['uz'].get(key, key))
    return list(variants)
